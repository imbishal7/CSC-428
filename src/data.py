HW_TABLE = np.array([bin(i).count("1") for i in range(256)], dtype=np.int64)
TARGET_BYTE = 2  # ASCAD convention: attack on the 3rd key byte


def _bundle(group):
    traces = np.array(group["traces"], dtype=np.float32)
    sbox_labels = np.array(group["labels"], dtype=np.int64)
    meta = group["metadata"]
    plaintexts = np.array(meta["plaintext"], dtype=np.uint8)
    keys = np.array(meta["key"], dtype=np.uint8)
    return traces, sbox_labels, plaintexts, keys


def load_ascad(path: str, label_kind: str = "hw"):
    """Load an ASCAD .h5 file.

    label_kind:
        "hw"   -> 9-class Hamming weight of Sbox(p[2] xor k[2])  (matches our proposal)
        "sbox" -> 256-class Sbox output                          (standard SCA target)
    """
    with h5py.File(path, "r") as f:
        Xp, Yp_sbox, Pp, Kp = _bundle(f["Profiling_traces"])
        Xa, Ya_sbox, Pa, Ka = _bundle(f["Attack_traces"])

    if label_kind == "hw":
        Yp = HW_TABLE[Yp_sbox]
        Ya = HW_TABLE[Ya_sbox]
    elif label_kind == "sbox":
        Yp, Ya = Yp_sbox, Ya_sbox
    else:
        raise ValueError(f"unknown label_kind {label_kind!r}")

    return {
        "X_profiling": Xp, "Y_profiling": Yp,
        "X_attack": Xa,    "Y_attack": Ya,
        "plaintext_profiling": Pp, "key_profiling": Kp,
        "plaintext_attack":    Pa, "key_attack":    Ka,
    }


def fit_scaler(X_profiling: np.ndarray) -> StandardScaler:
    return StandardScaler().fit(X_profiling)


def apply_scaler(scaler: StandardScaler, X: np.ndarray) -> np.ndarray:
    return scaler.transform(X).astype(np.float32)


def crop_to_len(X: np.ndarray, n: int) -> np.ndarray:
    """Center-crop traces to length `n`. Variable-key ASCAD uses 1400-sample traces
    while fixed-key uses 700; calling this before scaling lets a 700-input model
    consume both."""
    cur = X.shape[1]
    if cur == n:
        return X
    if cur < n:
        raise ValueError(f"trace length {cur} is shorter than required {n}; cannot crop")
    start = (cur - n) // 2
    return X[:, start:start + n]


def augment_shift(X: np.ndarray, max_shift: int, rng: np.random.Generator | None = None) -> np.ndarray:
    """Random circular time-shift per trace; mimics jitter for training-time augmentation."""
    if max_shift <= 0:
        return X
    rng = rng or np.random.default_rng()
    shifts = rng.integers(-max_shift, max_shift + 1, size=X.shape[0])
    out = np.empty_like(X)
    for i, s in enumerate(shifts):
        out[i] = np.roll(X[i], s)
    return out


def augment_noise(X: np.ndarray, sigma: float, rng: np.random.Generator | None = None) -> np.ndarray:
    if sigma <= 0:
        return X
    rng = rng or np.random.default_rng()
    return X + rng.normal(0.0, sigma, size=X.shape).astype(X.dtype)
